# Helper: escape a Chinese string to \uXXXX
def u(s):
    r = []
    for ch in s:
        cp = ord(ch)
        if cp > 127:
            r.append('\\u' + format(cp, '04x'))
        else:
            r.append(ch)
    return ''.join(r)

