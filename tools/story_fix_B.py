def main():
    d = json.load(open(SRC, encoding="utf-8"))
    ts = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    bak = os.path.join(ROOT, "data", "cultural.json.bak_storyfixB_" + ts)
    json.dump(d, open(bak, "w", encoding="utf-8"), ensure_ascii=False)
    print("backup ->", os.path.basename(bak))

    report = ["# B 线 story 杜撰修正复核报告", "",
              "> 修正依据：汉典 zdic.net「基本解释」+ characters.json 的 shuowen（《说文》原文）。",
              "> 修正原则：保留「字源故事」综合描述风格，但把与说文本义冲突的杜撰字源改写为权威本义；不引入新错误。", "",
              "| 字 | 旧 story（杜撰/错误摘录） | 新 story（已修正） | 说文本义依据 |",
              "|---|---|---|---|"]
    applied = []
    for ch, (new_story, basis) in FIX.items():
        v = d.get(ch)
        if not v:
            report.append(f"| {ch} | (cultural.json 无此字) | — | {basis} |")
            continue
        old = v.get("story", "")
        v["story"] = new_story
        applied.append(ch)
        # 旧 story 摘录：取前 40 字
        old_excerpt = old[:40] + ("…" if len(old) > 40 else "")
        report.append(f"| {ch} | {old_excerpt} | {new_story[:60]}… | {basis} |")
    json.dump(d, open(SRC, "w", encoding="utf-8"), ensure_ascii=False)
    rep_path = os.path.join(ROOT, "tools", "story_fix_B.md")
    open(rep_path, "w", encoding="utf-8").write("\n".join(report) + "\n")
    print("applied:", applied)
    print("report ->", os.path.basename(rep_path))
    print("cultural.json stories updated:", len(applied))

if __name__ == "__main__":
    main()
