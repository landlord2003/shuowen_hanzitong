def norm(s):
    return re.sub(r"[^\u4e00-\u9fff]", "", s)

# 建索引
IDX = {}
for line, src in VERIFIED:
    IDX[norm(line)] = src

def lookup(line):
    n = norm(line)
    if n in IDX:
        return IDX[n]
    # 从句切分精确匹配（仅主干名句，长度>=6）
    for sep in ["，", "。", "；", "、"]:
        parts = line.split(sep)
        for p in parts:
            pn = norm(p)
            if len(pn) >= 6 and pn in IDX:
                return IDX[pn]
    return None

def main():
    d = json.load(open(CULT, encoding="utf-8"))
    total = 0
    pending0 = 0
    recovered = 0
    skipped = []  # 已非待考（理论上无）
    samples = []
    for ch, v in d.items():
        if not isinstance(v, dict):
            continue
        for pm in (v.get("poems") or []):
            if not isinstance(pm, dict):
                continue
            total += 1
            src = pm.get("source", "")
            if src and "待考" not in src and "示例" not in src and "未知" not in src:
                pending0 += 0
                skipped.append((ch, pm.get("line", ""), src))
                continue
            hit = lookup(pm.get("line", ""))
            if hit:
                pm["source"] = hit
                recovered += 1
                if len(samples) < 25:
                    samples.append((ch, pm.get("line", ""), hit))
            # 未命中保持待考
    json.dump(d, open(CULT, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    print(f"total poems: {total}")
    print(f"recovered (待考 -> 真出处): {recovered}")
    print(f"still 待考: {total - recovered - len(skipped)}")
    if skipped:
        print(f"already-had-source (should be 0): {len(skipped)}")
    print("--- sample recovered ---")
    for ch, line, src in samples:
        print(f"  {ch} | {line}  =>  {src}")

if __name__ == "__main__":
    main()
