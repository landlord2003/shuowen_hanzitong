def main():
    data = json.load(open(CHAR_PATH, encoding="utf-8"))
    chars = data["characters"]

    n_radical = 0
    n_meaning = 0
    n_none = 0
    stats = Counter()

    for c in chars:
        wuxing = ""
        source = ""
        rad = c.get("radical", "")
        ch = c["char"]

        # 优先级：字义 > 偏旁（主流字源五行法：字义经假借/转注变化后，须按新字义定五行）
        # 1. 字义法（五行理论清单）
        if ch in WUXING_MEANING:
            wuxing = WUXING_MEANING[ch]
            source = "字义"
            n_meaning += 1
        # 2. 偏旁部首法
        elif rad in WUXING_RADICAL:
            wuxing = WUXING_RADICAL[rad]
            source = "偏旁"
            n_radical += 1
        # 3. 无明确
        else:
            wuxing = "无明确"
            source = "无明确"
            n_none += 1

        c["wuxing"] = wuxing
        c["wuxing_source"] = source
        stats[wuxing] += 1

    json.dump(data, open(CHAR_PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    total = len(chars)
    print(f"总字数: {total}")
    print(f"  偏旁法: {n_radical} ({n_radical/total*100:.1f}%)")
    print(f"  字义法: {n_meaning} ({n_meaning/total*100:.1f}%)")
    print(f"  无明确: {n_none} ({n_none/total*100:.1f}%)")
    print()
    print("五行分布:", dict(stats.most_common()))


if __name__ == "__main__":
    main()
