def build_json():
    """构建核心 JSON 数据文件"""
    data = {
        "meta": {
            "name": "说文解字 · 汉字知识库",
            "version": "1.0",
            "total_chars": len(CHARACTERS),
            "description": "简体字到繁体字到甲骨文的演变对照，今义与本义对比",
            "created": "2026-07-07",
            "fields": [
                "char (简体)", "trad (繁体)", "pinyin (拼音)",
                "radical (部首)", "radical_name (部首名)", "stroke (笔画)",
                "liushu (六书)", "original (本义)", "modern (今义)",
                "shuowen (说文释文)", "evolution (演变描述)",
                "oracle_id (EVOBC数据集ID, 0=未收录)"
            ]
        },
        "characters": []
    }

    for i, c in enumerate(CHARACTERS):
        entry = {
            "id": i + 1,
            "char": c["char"],
            "trad": c["trad"],
            "pinyin": c["pinyin"],
            "radical": c["radical"],
            "radical_name": c["radical_name"],
            "stroke": c["stroke"],
            "liushu": c["liushu"],
            "original": c["original"],
            "modern": c["modern"],
            "shuowen": c["shuowen"],
            "evolution": c["evolution"],
            "oracle_id": c.get("oracle_id", 0)
        }
        # Optional fields
        if c.get("oracle_note"):
            entry["oracle_note"] = c["oracle_note"]
        if c.get("oracle_char"):
            entry["oracle_char"] = c["oracle_char"]
        if c.get("related_glyphs"):
            entry["related_glyphs"] = c["related_glyphs"]
        data["characters"].append(entry)

    # Save JSON
    output_dir = os.path.dirname(os.path.abspath(__file__))
    json_path = os.path.join(output_dir, "data", "characters.json")
    os.makedirs(os.path.join(output_dir, "data"), exist_ok=True)

    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"JSON 数据已生成: {json_path}")
    print(f"共收录 {len(CHARACTERS)} 个汉字")
    return data


def build_obsidian(data):
    """生成 Obsidian Markdown 文件"""
    output_dir = os.path.dirname(os.path.abspath(__file__))
    obsidian_dir = os.path.join(output_dir, "obsidian", "汉字库")
    os.makedirs(obsidian_dir, exist_ok=True)

    # 六书统计
    liushu_count = {}
    for entry in data["characters"]:
        ls = entry["liushu"]
        liushu_count[ls] = liushu_count.get(ls, 0) + 1

    for entry in data["characters"]:
        c = entry["char"]
        filename = f"{c}_{entry['pinyin']}.md"
        filepath = os.path.join(obsidian_dir, filename)

        liushu = entry["liushu"]
        liushu_tag = f"六书/{liushu}"
        radical_tag = f"部首/{entry['radical']}"

        md = f"""---
aliases: ["{c}", "{entry['trad']}"]
tags: [汉字, {liushu_tag}, {radical_tag}]
pinyin: {entry['pinyin']}
radical: {entry['radical']}
stroke: {entry['stroke']}
liushu: {entry['liushu']}
created: 2026-07-07
---

# {c}

> **拼音**: {entry['pinyin']}　**繁体**: {entry['trad']}　**部首**: {entry['radical']}（{entry['radical_name']}）　**笔画**: {entry['stroke']}　**六书**: {entry['liushu']}

## 字形演变

```
{entry['evolution']}
```

## 本义（造字本义）

{entry['original']}

## 今义（现代常用义）

{entry['modern']}

## 《说文解字》

> {entry['shuowen']}
"""

        # 甲骨文特别说明
        oracle_note = entry.get("oracle_note", "")
        if oracle_note:
            md += f"\n## 甲骨文特别说明\n\n{oracle_note}\n"

        related = entry.get("related_glyphs", "")
        if related:
            md += f"\n## 相关字形\n\n{related}\n"

        md += """

---

"""

        md += "## 六书分类: [[" + liushu + "]]\n\n"
        md += """## 相关字词

## 笔记

"""
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(md)

    # 生成索引文件
    index_md = "# 汉字知识库索引\n\n"
    index_md += f"共收录 **{len(data['characters'])}** 个汉字\n\n"
    index_md += "## 六书分布\n\n"
    for ls, count in sorted(liushu_count.items(), key=lambda x: -x[1]):
        index_md += f"- {ls}: {count} 字\n"

    index_md += "\n## 按拼音索引\n\n"
    by_pinyin = sorted(data["characters"], key=lambda x: x["pinyin"])
    current_initial = ""
    for entry in by_pinyin:
        pinyin = entry["pinyin"]
        initial = pinyin[0] if pinyin else ""
        if initial != current_initial:
            current_initial = initial
            index_md += f"\n### {current_initial.upper()}\n\n"
        index_md += f"- [[{entry['char']}_{entry['pinyin']}|{entry['char']}]] `{entry['pinyin']}` {entry['liushu']}\n"

    index_path = os.path.join(obsidian_dir, "汉字知识库索引.md")
    with open(index_path, "w", encoding="utf-8") as f:
        f.write(index_md)

    print(f"Obsidian Markdown 已生成: {obsidian_dir}")
    print(f"共生成 {len(data['characters'])} 个汉字 + 1 个索引文件")


